        public const string MetricFileName = "oring-catalog-metrico.txt";

        public static string MetricDefaultPath =>
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
                         "AutoEDM", MetricFileName);

        /// <summary>Série dos anéis métricos, como aparece na designação ("DL 18,00 × 2,00 (7662)").</summary>
        public const string MetricSeries = "DL";

        /// <summary>
        /// Lê o catálogo métrico do disco; se não existir, grava a tabela embutida da DL Seals
        /// lá. Mesmo formato do AS568, com o 6º campo = composto (NBR/FKM). Nunca lança.
        /// </summary>
        public static ORingCatalog LoadOrCreateMetric(string path = null)
        {
            path = path ?? MetricDefaultPath;
            try
            {
                if (File.Exists(path))
                {
                    var loaded = Parse(File.ReadAllLines(path), MetricSeries);
                    Log.Info($"Catálogo métrico de O'ring: {loaded.Count} medida(s) de {path}.");
                    return loaded;
                }
            }
            catch (Exception e) { Log.Warn($"Catálogo métrico: falha ao ler {path} ({e.GetBaseException().Message}); usando a tabela embutida."); }

            var builtIn = BuiltInDlSealsMetric();
            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, RenderMetric(builtIn), new UTF8Encoding(false));
                Log.Info($"Catálogo métrico de O'ring criado em {path} ({builtIn.Count} medidas DL Seals).");
            }
            catch (Exception e) { Log.Warn("Catálogo métrico: não deu para gravar o arquivo: " + e.GetBaseException().Message); }
            return builtIn;
        }

        public static string RenderMetric(ORingCatalog catalog)
        {
            var sb = new StringBuilder();
            sb.AppendLine("\\ Catálogo MÉTRICO de anéis O'ring do AutoEDM — DL Seals, \"O'rings Milimétricos\" (set/2025).");
            sb.AppendLine("\\\\");
            sb.AppendLine("\\ Formato:  d1 ; d2 ; codigo ; conferido ; tolerancia ; composto");
            sb.AppendLine("\\   composto = NBR (Nitrílica 70 Shore) ou FKM (Viton) — o anel só é oferecido no elastômero dele");
            sb.AppendLine("\\ Decimal com ponto ou vírgula. Linhas começando com \\ ou # são comentário.");
            sb.AppendLine("\\ Só entra na escolha com a caixa \"Incluir anéis métricos\" marcada na janela.");
            foreach (var s in catalog.Sizes.OrderBy(x => x.Material).ThenBy(x => x.CrossSection).ThenBy(x => x.InnerDiameter))
                sb.AppendLine(string.Format(CultureInfo.InvariantCulture, "{0,8:0.00} ; {1,5:0.00} ; {2,-6} ; {3} ; {4:0.00} ; {5}",
                    s.InnerDiameter, s.CrossSection, s.Code ?? "", s.Verified ? "1" : "0", s.Tolerance,
                    s.Material == Elastomer.Fkm ? "FKM" : s.Material == Elastomer.Nbr ? "NBR" : ""));
            return sb.ToString();
        }

        /// <summary>A tabela DL Seals embutida (d1 ; d2 ; código ; composto), marcada como
        /// CONFERIDA — é o catálogo do próprio fornecedor.</summary>
        public static ORingCatalog BuiltInDlSealsMetric()
        {
            var sizes = new List<ORingSize>();
            foreach (string raw in DlSealsTable.Split('\n'))
            {
                string line = raw.Trim();
                if (line.Length == 0) continue;
                var f = line.Split(';');
                sizes.Add(new ORingSize
                {
                    InnerDiameter = double.Parse(f[0], CultureInfo.InvariantCulture),
                    CrossSection = double.Parse(f[1], CultureInfo.InvariantCulture),
                    Code = f[2],
                    Series = MetricSeries,
                    Verified = true,
                    Material = f[3] == "FKM" ? Elastomer.Fkm : Elastomer.Nbr
                });
            }
            return new ORingCatalog(sizes);
        }

